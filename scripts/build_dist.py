"""Assemble dist/ for Cloudflare Workers static assets: the app from web/, the one data version
web/data/current.json names, the photos that version's cards use (web/data/photos/, listed in its photos.json), and a
_headers file. The release gate (pipeline.s99_validate) runs first.

    uv run python scripts/build_dist.py             # preview: pending-O1 sources allowed, noindex; a preview build, not for the public site
    uv run python scripts/build_dist.py --release   # public: refused unless s99_validate --release passes
    uv run python scripts/build_dist.py --allow-dirty   # with uncommitted changes to web/: for a local look only

Limits and _headers rules: https://developers.cloudflare.com/workers/platform/limits/ and
https://developers.cloudflare.com/workers/static-assets/headers/
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
DIST = ROOT / "dist"
DATA = ROOT / "data"
# What each data version held when it was built, {version: {file: sha256}}; outside dist/ so it outlives rebuilds,
# and ignored by git. Browsers keep /data/<version>/ for a year, so a version name must never change content.
RECORD = ROOT / ".dist-versions.json"
SHIPPING = ["web", "scripts/build_dist.py", "wrangler.jsonc"]  # what decides dist/'s content; must be committed

# Workers static assets, Free plan (checked 2026-10-15): 20,000 files per Worker version, 25 MiB per file,
# 100 _headers rules, 2,000 characters per _headers line.
CF_MAX_FILES = 20_000
CF_MAX_FILE_BYTES = 25 * 1024 * 1024
CF_MAX_HEADER_RULES = 100
CF_MAX_HEADER_LINE = 2_000

DEV_DIRS = {"data", "test"}  # web/data ships separately (one version only); web/test is node --test's
PHOTO_KEY = re.compile(r"[0-9a-f]{16}-\d+\.(jpg|png|webp)")  # s06_wiki's content-addressed photo names
VERSION_RE = re.compile(r"v[A-Za-z0-9_-]+")  # a folder name, safe inside a _headers path pattern

# What the page loads (app.js, worker.js, gz.js): module scripts and a module worker from this origin, fetch() of
# this origin's data, self-hosted fonts. Inline style attributes are set in app.js's templates (legend swatches,
# the card's colour band), hence 'unsafe-inline' for styles only. index.html's favicon is `data:,`.
# Quests (config.features.quests, roadmap 24) show Wikimedia Commons thumbnails (app.js, clue.thumb): when quests.json
# ships, add their host (upload.wikimedia.org) to img-src, or every quest photo is blocked.
CSP = "; ".join([
    "default-src 'self'",
    "script-src 'self'",
    "worker-src 'self'",
    "connect-src 'self'",
    "font-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
])
IMMUTABLE = "public, max-age=31536000, immutable"
REVALIDATE = "public, max-age=0, must-revalidate"
WEEK = "public, max-age=604800"


def headers(version: str, *, release: bool) -> str:
    """The _headers file. Every request gets the security headers (and noindex on a preview); each path gets
    Cache-Control from exactly one rule, because Cloudflare joins a header two matching rules both set.

    The *.bin.gz files are the pipeline's gzip bytes, which the page unpacks itself (web/gz.js). Wrangler types
    them from the extension (application/gzip, never with a Content-Encoding), and Cloudflare compresses only
    text-like types, so they travel as stored; Content-Type: application/octet-stream makes that explicit."""
    everywhere = ["X-Content-Type-Options: nosniff", "Referrer-Policy: no-referrer",
                  f"Content-Security-Policy: {CSP}"]
    if not release:
        everywhere.append("X-Robots-Tag: noindex")
    blocks = [
        ("/*", everywhere),
        # versioned data never changes under its name: a new build is a new vYYYYMMDD folder; a photo's name is its
        # Commons file's sha1, so it never changes either
        (f"/data/{version}/*", [f"Cache-Control: {IMMUTABLE}"]),
        ("/data/photos/*", [f"Cache-Control: {IMMUTABLE}"]),
        (f"/data/{version}/*.gz", ["Content-Type: application/octet-stream"]),
        # the pointer to the current version, and the app's unversioned files (no build step), revalidate each time
        ("/data/current.json", ["Cache-Control: no-cache"]),
        ("/", [f"Cache-Control: {REVALIDATE}"]),
        ("/*.html", [f"Cache-Control: {REVALIDATE}"]),
        ("/*.js", [f"Cache-Control: {REVALIDATE}"]),
        ("/*.css", [f"Cache-Control: {REVALIDATE}"]),
        ("/fonts/*", [f"Cache-Control: {WEEK}"]),
    ]
    kind = "release" if release else "PREVIEW (noindex; a preview build: not for the public site)"
    lines = [f"# Generated by scripts/build_dist.py for {version}, {kind}. Rebuilt on every build: edit the script."]
    for path, hs in blocks:
        lines += ["", path, *(f"  {h}" for h in hs)]
    text = "\n".join(lines) + "\n"
    too_long = [line for line in text.splitlines() if len(line) > CF_MAX_HEADER_LINE]
    if len(blocks) > CF_MAX_HEADER_RULES or too_long:
        raise SystemExit(f"build_dist: _headers is over Cloudflare's limits ({len(blocks)} rules, "
                         f"{len(too_long)} lines over {CF_MAX_HEADER_LINE} characters)")
    return text


def current_version(web: Path) -> str:
    current = web / "data" / "current.json"
    if not current.is_file():
        raise SystemExit(f"build_dist: {current} is missing: build the data first (uv run python -m pipeline.run)")
    version = json.loads(current.read_text(encoding="utf-8")).get("version")
    if not isinstance(version, str) or not VERSION_RE.fullmatch(version):
        raise SystemExit(f"build_dist: {current} names version {version!r}, which is not a vYYYYMMDD folder name")
    if not (web / "data" / version).is_dir():
        raise SystemExit(f"build_dist: {current} names {version}, but {web / 'data' / version} is missing")
    return version


def gate(version_dir: Path, data: Path, release: bool) -> list[str]:
    """The release gate: s99_validate's problems for this version (with release=True, pending-O1 sources too)."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from pipeline.s99_validate import validate

    return validate(version_dir, data, release=release)


def photo_files(web: Path, version: str) -> list[str]:
    """The photos the version's cards use (its photos.json, s03_tiles); each must be in web/data/photos/."""
    listing = web / "data" / version / "photos.json"
    keys = json.loads(listing.read_text(encoding="utf-8")) if listing.is_file() else []
    bad = [k for k in keys if not isinstance(k, str) or not PHOTO_KEY.fullmatch(k)]
    missing = [k for k in keys if k not in bad and not (web / "data" / "photos" / k).is_file()]
    if bad or missing:
        raise SystemExit(f"build_dist: {listing} names {len(bad)} bad and {len(missing)} missing photos "
                         "(run s06_wiki, which copies them to web/data/photos/)")
    return sorted(keys)


def files_in(folder: Path, skip: set[str] = frozenset()):
    """folder's files that ship, relative to it: no dotfiles (.DS_Store and the like) at any depth, and nothing
    under a top-level folder named in skip."""
    for p in sorted(folder.rglob("*")):
        rel = p.relative_to(folder)
        if p.is_file() and rel.parts[0] not in skip and not any(part.startswith(".") for part in rel.parts):
            yield rel


def app_files(web: Path):
    """web/'s files that ship: everything but web/data, web/test and dotfiles."""
    return files_in(web, DEV_DIRS)


def git_state(root: Path = ROOT) -> tuple[str, list[str]]:
    """HEAD's short sha, and `git status --porcelain` lines for uncommitted changes to SHIPPING (untracked files
    included). If git cannot tell, that counts as a change."""
    def git(*args: str) -> str:
        return subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True, text=True).stdout

    try:
        return git("rev-parse", "--short", "HEAD").strip(), \
            git("status", "--porcelain", "--untracked-files=all", "--", *SHIPPING).splitlines()
    except (OSError, subprocess.CalledProcessError) as e:
        return "unknown", [f"git status failed: {e}"]


def fingerprint(folder: Path) -> dict[str, str]:
    """sha256 of each file of a data version that ships."""
    return {rel.as_posix(): hashlib.sha256((folder / rel).read_bytes()).hexdigest() for rel in files_in(folder)}


def recorded() -> dict:
    return json.loads(RECORD.read_text(encoding="utf-8")) if RECORD.is_file() else {}


def check_unchanged(version: str, prints: dict[str, str], web: Path) -> None:
    """Refuse a version whose files differ from what an earlier build of that name held. The pipeline writes
    today's vYYYYMMDD folder in place on every run that day, but browsers keep /data/<version>/ for a year
    (immutable): a viewer would keep the old files, or mix old and new ones."""
    before = recorded().get(version)
    if before is None or before == prints:
        return
    changed = sorted(set(before) ^ set(prints) | {f for f in before.keys() & prints.keys() if before[f] != prints[f]})
    taken = {p.name for p in (web / "data").iterdir()} | set(recorded())
    base, n = version.split("-")[0], 2
    while f"{base}-{n}" in taken:
        n += 1
    more = f" and {len(changed) - 5} more" if len(changed) > 5 else ""
    raise SystemExit(
        f"build_dist: web/data/{version} has changed since it was built ({', '.join(changed[:5])}{more}). Browsers "
        f"keep /data/{version}/ for a year, so a version name must never change content. Rebuild the web data under "
        f"a new name (s03_tiles points current.json at it), then build again:\n"
        f"  uv run python -m pipeline.run s03_tiles s04_base s07_labels s14_search s99_validate -- --version {base}-{n}\n"
        f"What each version held when it was built: {RECORD}")


def remember(version: str, prints: dict[str, str]) -> None:
    record = recorded()
    record[version] = prints
    RECORD.write_text(json.dumps(record, indent=1, sort_keys=True) + "\n", encoding="utf-8")


def clear(out: Path) -> None:
    """Make way for a fresh build. Only an empty folder or one this script built (it has a _headers file) is
    replaced, so a mistyped --out cannot wipe web/ or the repository."""
    if not out.exists():
        return
    if any(out.iterdir()) and not (out / "_headers").is_file():
        raise SystemExit(f"build_dist: {out} is not empty and was not built by this script; choose another --out")
    shutil.rmtree(out)


def check_limits(out: Path) -> tuple[int, int, Path, int]:
    """Count, total bytes and largest of the served files (_headers is configuration, not an asset); exits if any
    Cloudflare limit is exceeded."""
    served = [p for p in out.rglob("*") if p.is_file() and p.relative_to(out).as_posix() != "_headers"]
    sizes = {p.relative_to(out): p.stat().st_size for p in served}
    over = [f"{rel} is {n:,} bytes" for rel, n in sorted(sizes.items()) if n > CF_MAX_FILE_BYTES]
    if over:
        raise SystemExit(f"build_dist: over Cloudflare's {CF_MAX_FILE_BYTES:,}-byte file limit: {'; '.join(over)}")
    if len(sizes) > CF_MAX_FILES:
        raise SystemExit(f"build_dist: {len(sizes):,} files, over Cloudflare's limit of {CF_MAX_FILES:,} files")
    largest = max(sizes, key=sizes.get)
    return len(sizes), sum(sizes.values()), largest, sizes[largest]


def mb(n: int) -> str:
    return f"{n / 1_000_000:.1f} MB"


def build(out: Path = DIST, *, web: Path = WEB, data: Path = DATA, release: bool = False,
          allow_dirty: bool = False) -> None:
    out, web = Path(out), Path(web)
    head, dirty = git_state()
    listed = "".join(f"\n  {line}" for line in dirty)
    if dirty and not allow_dirty:
        raise SystemExit("build_dist: uncommitted changes to what ships; commit them first (or --allow-dirty for a "
                         f"local look, never a deploy):{listed}")
    version = current_version(web)
    prints = fingerprint(web / "data" / version)
    check_unchanged(version, prints, web)
    errors = gate(web / "data" / version, Path(data), release)
    if errors:
        print(f"build_dist: the release gate (s99_validate{' --release' if release else ''}) failed for {version}; "
              "nothing was built:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        raise SystemExit(1)
    if release:
        print(f"build_dist: {version} passes the release gate (s99_validate --release): public build")
    else:
        blocking = gate(web / "data" / version, Path(data), True)
        print(f"build_dist: PREVIEW ONLY: a preview build: not for the public site. {version} passes s99_validate, "
              + ("and also --release: build with --release for a public site." if not blocking
                 else "but not --release yet:"))
        for e in blocking:
            print(f"  - {e}")
    if dirty:
        print(f"build_dist: built WITH uncommitted changes (--allow-dirty), not for deploying:{listed}")

    photos = photo_files(web, version)   # before anything is written: a missing photo leaves dist/ as it was
    clear(out)
    for rel in app_files(web):
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(web / rel, out / rel)
    if not (out / "index.html").is_file():
        raise SystemExit(f"build_dist: {web / 'index.html'} is missing")
    (out / "data").mkdir()
    shutil.copy2(web / "data" / "current.json", out / "data" / "current.json")
    shutil.copytree(web / "data" / version, out / "data" / version, ignore=shutil.ignore_patterns(".*"))
    if photos:
        (out / "data" / "photos").mkdir()
    for key in photos:
        shutil.copy2(web / "data" / "photos" / key, out / "data" / "photos" / key)
    (out / "_headers").write_text(headers(version, release=release), encoding="utf-8")

    n, total, largest, size = check_limits(out)
    remember(version, prints)
    print(f"build_dist: {out}: {n} files, {mb(total)}; largest {largest.as_posix()} ({mb(size)}); "
          f"commit {head}{' plus uncommitted changes' if dirty else ''}, data {version}")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="build_dist", description=__doc__.splitlines()[0])
    ap.add_argument("--release", action="store_true",
                    help="public build: require s99_validate --release to pass, and drop noindex")
    ap.add_argument("--out", default=str(DIST), help=f"output folder (default {DIST.relative_to(ROOT)})")
    ap.add_argument("--allow-dirty", action="store_true",
                    help="build even with uncommitted changes to web/, this script or wrangler.jsonc (local look only)")
    args = ap.parse_args(argv)
    build(Path(args.out), release=args.release, allow_dirty=args.allow_dirty)


if __name__ == "__main__":
    main(sys.argv[1:])
